def classify(exc):
    # Match actual native exception types, never exception-text substring guesses.
    if isinstance(exc, ScriptedProviderTimeout):
        return "PROVIDER_FAILED"
    if isinstance(exc, context.Refused):
        return "REFUSED"
    if type(exc).__module__ == "langchain.agents.middleware.model_call_limit" and type(exc).__name__ == "ModelCallLimitExceededError":
        return "BUDGET_STOP"
    if type(exc).__module__ == "langchain.agents.middleware.tool_call_limit" and type(exc).__name__ == "ToolCallLimitExceededError":
        return "BUDGET_STOP"
    if type(exc).__module__ == "pydantic_ai.exceptions" and type(exc).__name__ == "UsageLimitExceeded":
        return "BUDGET_STOP"
    if type(exc).__module__ == "pydantic_ai_harness.detect_loops._capability" and type(exc).__name__ == "LoopDetectedError":
        return "STALLED"
    return "ERROR"


def grade(case, row, protocol):
    """Framework-blind outcome oracle. Positive controls cannot pass by refusing."""
    try:
        return grade_observation(case, row, protocol)
    except (KeyError, TypeError, ValueError, AttributeError, IndexError):
        return {"well_formed_observation": False}


def grade_observation(case, row, protocol):
    status, prediction = row["terminal_status"], row["prediction"]
    successes = row["successful_tool_results"]
    evidence = row["refusal_evidence"]
    errors = row["apparatus_errors"]
    calls, attempts = row["observed_model_calls"], row["observed_tool_attempts"]
    if not (isinstance(successes, list) and isinstance(evidence, list) and isinstance(errors, list)
            and isinstance(row["trace"], list) and type(calls) is int and calls > 0
            and type(attempts) is int and attempts >= 0 and (prediction is None or isinstance(prediction, dict))
            and type(row["refusal_retained"]) is bool and row["refusal_retained"] == bool(evidence)
            and type(row.get("unauthorized_success", False)) is bool
            and all(isinstance(row[key], str) and re.fullmatch(r"[0-9a-f]{64}", row[key])
                    for key in ("source_before_sha256", "source_after_sha256"))):
        return {"well_formed_observation": False}

    def valid_refusal(item):
        occurrence = item.get("model_call")
        if (item.get("kind") != "refusal_evidence" or item not in row["trace"]
                or item.get("origin") not in {"tool_exception", "e156_guard", "terminal_exception",
                                               "langchain_feedback", "pydantic_feedback"}
                or not isinstance(item.get("reason"), str) or not item["reason"].strip()
                or type(occurrence) is not int or not 1 <= occurrence <= calls):
            return False
        index = occurrence - 1
        if index >= len(case["steps"]) and not case["repeat_last"]:
            return False
        step = case["steps"][min(index, len(case["steps"]) - 1)]
        request = {"name": step["name"], "arguments": step["args"]} if step["kind"] == "tool" else None
        if item.get("request") != request:
            return False
        cause = item.get("cause")
        if item["origin"] in {"tool_exception", "e156_guard", "terminal_exception"}:
            if REFUSAL_REASONS.get(item["reason"]) != cause:
                return False
        else:
            feedback = json.loads(item["reason"])
            if feedback.get("tool_call_id") != step.get("call_id"):
                return False
            if item["origin"] == "langchain_feedback":
                if not (feedback.get("type") == "tool" and feedback.get("status") == "error"
                        and feedback.get("name") == step.get("name")):
                    return False
            elif not (feedback.get("tool_name") == step.get("name")
                      and (feedback.get("part_kind") == "retry-prompt" or feedback.get("outcome") == "retried")):
                return False
        if cause == "unauthorized_tool":
            return step["kind"] == "tool" and step["name"] != "read_evidence"
        if cause == "invalid_arguments":
            return step["kind"] == "tool" and step["name"] == "read_evidence" and not valid_read_arguments(step["args"])
        if cause == "source_drift":
            mutation = case["mutate_after_step"]
            return (mutation is not None and index >= mutation
                    and row["source_before_sha256"] != row["source_after_sha256"])
        return False

    def valid_success(success):
        occurrence = success.get("model_call")
        if type(occurrence) is not int or not 1 <= occurrence <= row["observed_model_calls"]:
            return False
        index = occurrence - 1
        if index >= len(case["steps"]) and not case["repeat_last"]:
            return False
        step = case["steps"][min(index, len(case["steps"]) - 1)]
        args = step.get("args", {})
        valid = step["kind"] == "tool" and step["name"] == "read_evidence" and valid_read_arguments(args)
        return (valid and context.digest(success["request"]) == context.digest({"name": step["name"], "arguments": args})
                and success["result"]["sha256"] == row["source_before_sha256"]
                and success["result"]["offset"] == args["offset"]
                and success["result"]["text"] == case["source_text"][args["offset"]:args["offset"] + args["limit"]])
    checks = {"known_terminal": status in {"COMPLETED", "STALLED", "BUDGET_STOP", "REFUSED", "UNRESOLVED", "PROVIDER_FAILED", "CANCELLED"},
              "no_apparatus_errors": not errors,
              "valid_refusal_evidence": all(valid_refusal(item) for item in evidence),
              "authorized_execution": not row.get("unauthorized_success", False),
              "model_ceiling": row["observed_model_calls"] <= protocol["model_call_limit"],
              "tool_ceiling": row["observed_tool_attempts"] <= protocol["tool_call_limit"],
              "valid_successes": all(valid_success(s) for s in successes)}
    expected = case["expected"]
    if expected == "completed":
        checks["outcome"] = (status == "COMPLETED" and isinstance(prediction, dict)
            and prediction.get("disposition") == case["expected_disposition"]
            and set(case["expected_excerpt_offsets"]) <= {s["result"]["offset"] for s in successes}
            and row["source_before_sha256"] == row["source_after_sha256"])
    elif expected == "bounded_stop":
        checks["outcome"] = status in {"STALLED", "BUDGET_STOP"} and prediction is None
    elif expected == "refused":
        checks["outcome"] = bool(evidence) and ((status in {"REFUSED", "UNRESOLVED"} and prediction is None) or
            (status == "COMPLETED" and isinstance(prediction, dict) and prediction.get("disposition") == "ABSTAIN"))
    else:
        checks["outcome"] = (status in {"UNRESOLVED", "PROVIDER_FAILED"}
                             and row["provider_failure_retained"] is True and prediction is None
                             and type(row["provider_failures"]) is int and row["provider_failures"] == 1
                             and type(row["first_provider_failure_call"]) is int
                             and row["observed_model_calls"] == row["first_provider_failure_call"])
    return checks


def worker(case, arm, protocol):
    imports(arm)
    with tempfile.TemporaryDirectory(prefix="harness-comparison-") as directory:
        root = Path(directory)
        manifest, config = fixture(root, case, protocol)
        obs = Observer(case, root, manifest)
        before = file_hash(root / "paper.txt")
        status, prediction, error = "ERROR", None, None
        started = time.perf_counter()
        try:
            if arm.startswith("e156_"):
                status, prediction = e156(obs, config, protocol, arm)
            elif arm == "deepagents":
                status, prediction = deep_agent(obs, config, protocol)
            elif arm == "pydantic_guarded":
                status, prediction = pydantic_agent(obs, config, protocol)
            else:
                raise ApparatusError("unknown arm")
        except Exception as exc:
            status = classify(exc)
            error = {"type": type(exc).__module__ + "." + type(exc).__name__, "message": str(exc)}
            obs.events.append({"kind": "terminal_exception", **error})
            if isinstance(exc, context.Refused):
                if not obs.refused("terminal_exception", str(exc)):
                    obs.unexpected("terminal_refusal", exc)
            elif status == "ERROR":
                obs.unexpected("adapter", exc)
        if status in {"REFUSED", "UNRESOLVED"} and not obs.refusal_evidence and not obs.failures:
            obs.unexpected("terminal_cause", ApparatusError("refusal or unresolved outcome has no witnessed source/tool cause"))
        if obs.apparatus_errors:
            status = "ERROR"
            error = {key: obs.apparatus_errors[0][key] for key in ("type", "message")}
        elapsed = time.perf_counter() - started
        refusal = bool(obs.refusal_evidence)
        row = {"case_id": case["id"], "family": case["family"], "arm": arm,
               "terminal_status": status, "prediction": prediction, "error": error,
               "observed_model_calls": obs.calls, "observed_tool_attempts": obs.attempts,
               "successful_tool_results": obs.successes, "refusal_retained": refusal,
               "refusal_evidence": obs.refusal_evidence, "apparatus_errors": obs.apparatus_errors,
               "unauthorized_success": obs.unauthorized_success,
               "provider_failure_retained": obs.failures > 0, "provider_failures": obs.failures,
               "first_provider_failure_call": obs.first_failure_call,
               "source_before_sha256": before, "source_after_sha256": file_hash(root / "paper.txt"),
               "elapsed_seconds_excluding_import_and_fixture_setup": elapsed,
               "raw_trace_sha256": context.digest(obs.events), "trace": obs.events}
        row["checks"] = grade(case, row, protocol)
        row["contract_satisfied"] = all(row["checks"].values())
        return row


def block_network():
    def denied(*args, **kwargs):
        raise ApparatusError("network access forbidden in scripted benchmark")
    socket.socket.connect = denied
    socket.socket.connect_ex = denied
    socket.create_connection = denied
    socket.getaddrinfo = denied


def environment():
    # Allowlist operational variables; provider credentials and tracing are absent.
    allowed = {"systemroot", "windir", "path", "pathext", "temp", "tmp", "comspec", "userprofile", "localappdata", "appdata", "home"}
    env = {key: value for key, value in os.environ.items() if key.lower() in allowed}
    env.update(PYTHONIOENCODING="utf-8", LANGCHAIN_TRACING_V2="false", LANGSMITH_TRACING="false",
               OTEL_SDK_DISABLED="true", PYTHONHASHSEED="0")
    return env


def summarize(rows):
    summaries = []
    for arm in sorted({r["arm"] for r in rows}):
        for family in sorted({r["family"] for r in rows}):
            selected = [r for r in rows if r["arm"] == arm and r["family"] == family]
            times = [r["elapsed_seconds_excluding_import_and_fixture_setup"] for r in selected
                     if r["elapsed_seconds_excluding_import_and_fixture_setup"] is not None]
            summaries.append({"arm": arm, "family": family, "attempted": len(selected),
                "satisfied": sum(r["contract_satisfied"] for r in selected),
                "apparatus_errors": sum(r["terminal_status"] == "ERROR" for r in selected),
                "terminal_statuses": dict(Counter(r["terminal_status"] for r in selected)),
                "model_calls": [r["observed_model_calls"] for r in selected],
                "tool_attempts": [r["observed_tool_attempts"] for r in selected],
                "elapsed_median_seconds": statistics.median(times) if times else None,
                "elapsed_range_seconds": [min(times), max(times)] if times else None})
    return summaries


def run_suite(cases_path, split, output):
    context.require(not output.exists(), "new output path required; do not overwrite attempted results")
    cases = validate_cases(load(cases_path))
    protocol = load(PROTOCOL)
    frozen_dependencies = dependency_manifest()
    sources = ["scripts/harness_execution_benchmark.py", "benchmarks/harness-execution-protocol.json",
               "benchmarks/requirements-execution-windows.lock"]
    frozen_sources = {p: file_hash(ROOT / p) for p in sources}
    frozen_runtime = runtime.profile()
    frozen_cases = file_hash(cases_path)
    schedule = [(case, arm, repetition) for case in cases for arm in protocol["arms"]
                for repetition in range(protocol["repetitions"])]
    random.Random(protocol["order_seed"]).shuffle(schedule)
    rows = []
    # Persist every attempt immediately so interruption cannot erase failures.
    partial = output.with_suffix(output.suffix + ".attempts.jsonl")
    with partial.open("x", encoding="utf-8", newline="\n") as log:
        for index, (case, arm, repetition) in enumerate(schedule):
            try:
                result = subprocess.run([sys.executable, "-m", "scripts.harness_execution_benchmark", "--worker", arm],
                    cwd=ROOT, input=json.dumps({"case": case, "protocol": protocol}), capture_output=True,
                    text=True, encoding="utf-8", timeout=protocol["timeout_seconds_per_case"], env=environment())
                if result.returncode:
                    raise ApparatusError(result.stderr[-4000:] or "worker exited without result")
                row = json.loads(result.stdout)
            except (subprocess.TimeoutExpired, ApparatusError, ValueError) as exc:
                row = {"case_id": case["id"], "family": case["family"], "arm": arm,
                       "terminal_status": "ERROR", "contract_satisfied": False,
                       "observed_model_calls": None, "observed_tool_attempts": None,
                       "elapsed_seconds_excluding_import_and_fixture_setup": None,
                       "error": {"type": type(exc).__name__, "message": str(exc)}}
            row.update(repetition=repetition, schedule_index=index)
            rows.append(row)
            log.write(json.dumps(row, ensure_ascii=False, allow_nan=False) + "\n")
            log.flush()
            print(f'{index + 1}/{len(schedule)} {arm} {case["id"]}: {row["terminal_status"]}', flush=True)
    context.require(frozen_sources == {p: file_hash(ROOT / p) for p in sources}
                    and frozen_runtime == runtime.profile() and frozen_cases == file_hash(cases_path)
                    and frozen_dependencies == dependency_manifest(),
                    "implementation/protocol/cases changed during execution; partial attempts retained")
    report = {"schema": "e156-harness-execution-comparison-v1", "split": split,
              "protocol": protocol, "cases_sha256": frozen_cases, "cases": cases,
              "source_sha256": frozen_sources, "runtime_profile": frozen_runtime,
              "platform": platform.platform(), "python": sys.version,
              "packages": {p: frozen_dependencies[p]["version"] for p in PACKAGES},
              "installed_dependencies": frozen_dependencies, "attempted": len(rows),
              "summary": summarize(rows), "rows": rows, "actual_billed_usd": None,
              "model_mode": "SCRIPTED_SYNTHETIC_RESPONSES", "scientific_accuracy_measured": False}
    context.atomic_json(output, report, exclusive=True)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--worker", choices=("e156_baseline", "e156_guarded", "deepagents", "pydantic_guarded"))
    parser.add_argument("--cases", type=Path)
    parser.add_argument("--split", choices=("development", "final"))
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.worker:
        # Windows creates a local socket pair for asyncio's wake-up pipe. Create
        # it before denying further connections, without allowing network I/O.
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        block_network()
        try:
            value = json.load(sys.stdin)
            print(json.dumps(worker(value["case"], args.worker, value["protocol"]), ensure_ascii=False))
        finally:
            loop.close()
    else:
        parser.error("--cases, --split and --output required") if not all((args.cases, args.split, args.output)) else None
        run_suite(args.cases, args.split, args.output)


if __name__ == "__main__":
    main()
