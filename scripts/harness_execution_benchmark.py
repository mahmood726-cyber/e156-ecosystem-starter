@dataclass
class Observer:
    case: dict
    root: Path
    manifest: dict
    events: list = field(default_factory=list)
    calls: int = 0
    failures: int = 0
    attempts: int = 0
    successes: list = field(default_factory=list)
    refusals: int = 0
    native_refusal: bool = False
    unauthorized_success: bool = False
    current_step: dict | None = None
    first_failure_call: int | None = None
    refusal_evidence: list = field(default_factory=list)
    apparatus_errors: list = field(default_factory=list)

    def refused(self, origin, reason, *, cause=None, model_call=None, step=None):
        """Retain a witnessed failure of a specific source/tool guard, not a status."""
        cause = cause or REFUSAL_REASONS.get(reason)
        if cause is None:
            return False
        step = self.current_step if step is None else step
        event = {"kind": "refusal_evidence", "origin": origin, "cause": cause, "reason": reason,
                 "model_call": self.calls if model_call is None else model_call,
                 "request": ({"name": step["name"], "arguments": step["args"]}
                             if step and step["kind"] == "tool" else None)}
        if event not in self.refusal_evidence:
            self.refusal_evidence.append(event)
            self.events.append(event)
        return True

    def unexpected(self, origin, exc):
        # The production journal deliberately converts callback failures to
        # UNRESOLVED. Observe them before that conversion without changing it.
        event = {"kind": "apparatus_exception", "origin": origin,
                 "type": type(exc).__module__ + "." + type(exc).__name__, "message": str(exc)}
        self.apparatus_errors.append(event)
        self.events.append(event)

    def feedback_refusal(self, dialect, message):
        call_id = message.get("tool_call_id")
        for event in reversed(self.events):
            step = event.get("script", {}) if event["kind"] == "model" else {}
            if step.get("kind") != "tool" or step["call_id"] != call_id:
                continue
            cause = ("unauthorized_tool" if step["name"] != "read_evidence" else
                     "invalid_arguments" if not valid_read_arguments(step["args"]) else None)
            if cause:
                self.refused(dialect + "_feedback", json.dumps(message, sort_keys=True), cause=cause,
                             model_call=event["index"] + 1, step=step)
            return

    def feedback(self, messages, dialect):
        for message in messages:
            if dialect == "langchain" and message.get("type") == "tool":
                self.native_refusal |= message.get("status") == "error"
                if message.get("status") == "error":
                    self.feedback_refusal(dialect, message)
                self.unauthorized_success |= message.get("status") == "success" and message.get("name") != "read_evidence"
            if dialect == "pydantic":
                for part in message.get("parts", []):
                    self.native_refusal |= part.get("part_kind") == "retry-prompt" or part.get("outcome") == "retried"
                    if part.get("part_kind") == "retry-prompt" or part.get("outcome") == "retried":
                        self.feedback_refusal(dialect, part)
                    self.unauthorized_success |= (part.get("part_kind") == "tool-return"
                        and part.get("outcome") == "success" and part.get("tool_name") != "read_evidence")

    def step(self, native_request):
        index = self.calls
        self.calls += 1
        steps = self.case["steps"]
        if index >= len(steps) and not self.case["repeat_last"]:
            raise ApparatusError("script exhausted; no response invented")
        step = steps[min(index, len(steps) - 1)]
        self.current_step = step
        self.events.append({"kind": "model", "index": index, "request": native_request, "script": step})
        if index == self.case["mutate_after_step"]:
            with (self.root / "paper.txt").open("a", encoding="utf-8", newline="\n") as handle:
                handle.write(DRIFT)
            self.events.append({"kind": "source_mutation", "index": index})
        if step["kind"] == "timeout":
            self.failures += 1
            if self.first_failure_call is None:
                self.first_failure_call = self.calls
            self.events.append({"kind": "provider_failure", "type": "ScriptedProviderTimeout", "model_call": self.calls})
            raise ScriptedProviderTimeout("synthetic provider timeout; outcome unknown")
        return step

    def invoke(self, request, execute):
        self.attempts += 1
        self.events.append({"kind": "tool_attempt", "request": request, "model_call": self.calls})
        try:
            result = execute()
        except context.Refused as exc:
            self.refusals += 1
            self.events.append({"kind": "tool_refusal", "reason": str(exc)})
            if not self.refused("tool_exception", str(exc)):
                self.unexpected("shared_tool", exc)
            raise
        except Exception as exc:
            self.unexpected("shared_tool", exc)
            raise
        self.successes.append({"request": request, "result": result, "model_call": self.calls})
        self.events.append({"kind": "tool_result", "result": result})
        return result

    def read(self, id: str, offset: int, limit: int):
        request = {"name": "read_evidence", "arguments": {"id": id, "offset": offset, "limit": limit}}
        def execute():
            context.require(id == "paper", "evidence outside common task scope")
            return context.excerpt(self.root, self.manifest, id, offset=offset, limit=limit)
        return self.invoke(request, execute)


def answer(step):
    result = {"disposition": step["disposition"], "reason": step["reason"]}
    if result["disposition"] == "ABSTAIN":
        result["stop_point"] = "SYNTHETIC_TEST_REFUSAL"
    return json.dumps(result, sort_keys=True)


def e156(obs, config, protocol, arm):
    if arm == "e156_guarded":
        config["progress_policy"] = {"repeated_result_limit": protocol["repeated_result_threshold"]}
    class Provider:
        def count(self, payload, timeout):
            obs.events.append({"kind": "input_count", "request": payload})
            return {"input_tokens": 20}

        def respond(self, payload, timeout):
            step = obs.step(payload)
            output = ([{"type": "function_call", "name": step["name"], "call_id": step["call_id"],
                        "arguments": json.dumps(step["args"], sort_keys=True)}] if step["kind"] == "tool" else
                      [{"type": "message", "role": "assistant", "content": [{"type": "output_text", "text": answer(step)}]}])
            return {"id": "synthetic-" + str(obs.calls), "status": "completed", "output": output,
                    "model": payload["model"], "service_tier": payload.get("service_tier", "default"),
                    "usage": {"input_tokens": 20, "output_tokens": 10, "total_tokens": 30}}
    original = runtime.Journal.operation
    original_require = runtime.require
    def observed_require(condition, message):
        try:
            return original_require(condition, message)
        except context.Refused as exc:
            if not obs.refused("e156_guard", str(exc)):
                obs.unexpected("e156_guard", exc)
            raise
    def instrument(journal, key, request, reserve, execute):
        def observed_execute(timeout):
            try:
                if key.startswith("tool:"):
                    result = obs.invoke(request, lambda: execute(timeout)[0])
                    return result, runtime.units(tool_calls=1)
                return execute(timeout)
            except ScriptedProviderTimeout:
                raise
            except context.Refused as exc:
                if str(exc) not in REFUSAL_REASONS:
                    obs.unexpected(key, exc)
                raise
            except Exception as exc:
                obs.unexpected(key, exc)
                raise
        return original(journal, key, request, reserve, observed_execute)
    runtime.Journal.operation = instrument
    runtime.require = observed_require
    try:
        report = runtime.run(config, obs.manifest, obs.root, obs.root / "state.sqlite", provider=Provider(), create=True)
        obs.events.append({"kind": "native_run", "report": report})
        return report["status"], report["prediction"]
    finally:
        runtime.Journal.operation = original
        runtime.require = original_require


def deep_agent(obs, config, protocol):
    from deepagents import create_deep_agent
    from langchain.agents.middleware import ModelCallLimitMiddleware, ToolCallLimitMiddleware
    from langchain_core.language_models.chat_models import BaseChatModel
    from langchain_core.messages import AIMessage
    from langchain_core.outputs import ChatResult, ChatGeneration
    from langchain_core.tools import StructuredTool
    from pydantic import PrivateAttr

    class ScriptedModel(BaseChatModel):
        _observer: Observer = PrivateAttr()
        @property
        def _llm_type(self):
            return "synthetic-benchmark-model"

        def bind_tools(self, tools, **kwargs):
            return self

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            request = [m.model_dump(mode="json") for m in messages]
            self._observer.feedback(request, "langchain")
            step = self._observer.step(request)
            message = (AIMessage(content="", tool_calls=[{"name": step["name"], "args": step["args"], "id": step["call_id"]}])
                       if step["kind"] == "tool" else AIMessage(content=answer(step)))
            return ChatResult(generations=[ChatGeneration(message=message)])
    model = ScriptedModel()
    model._observer = obs
    read_tool = StructuredTool.from_function(obs.read, name="read_evidence", description="Read a bounded excerpt of the synthetic paper.")
    agent = create_deep_agent(model=model, tools=[read_tool], subagents=[],
        system_prompt=runtime.SYSTEM,
        middleware=[ModelCallLimitMiddleware(run_limit=protocol["model_call_limit"], exit_behavior="error"),
                    ToolCallLimitMiddleware(run_limit=protocol["tool_call_limit"], exit_behavior="error")])
    prompt = config["task"] + "\nSynthetic source: " + obs.case["source_text"]
    result = agent.invoke({"messages": [{"role": "user", "content": prompt}]}, config={"recursion_limit": 100})
    messages = result["messages"]
    obs.feedback([m.model_dump(mode="json") for m in messages], "langchain")
    obs.events.append({"kind": "native_messages", "messages": [m.model_dump(mode="json") for m in messages]})
    return "COMPLETED", json.loads(messages[-1].content)


def pydantic_agent(obs, config, protocol):
    from pydantic_ai import Agent
    from pydantic_ai.messages import ModelResponse, ToolCallPart, TextPart, ModelMessagesTypeAdapter
    from pydantic_ai.models.function import FunctionModel
    from pydantic_ai.usage import UsageLimits, RequestUsage
    from pydantic_ai_harness.detect_loops import DetectLoops
    def response(messages, info):
        request = json.loads(ModelMessagesTypeAdapter.dump_json(messages))
        obs.feedback(request, "pydantic")
        step = obs.step(request)
        parts = ([ToolCallPart(step["name"], step["args"], tool_call_id=step["call_id"])] if step["kind"] == "tool"
                 else [TextPart(answer(step))])
        return ModelResponse(parts=parts, usage=RequestUsage(input_tokens=20, output_tokens=10))
    detector = DetectLoops(window=3, repeated_call_threshold=None,
        repeated_result_threshold=protocol["repeated_result_threshold"], alternating_calls_threshold=None,
        repeated_text_threshold=None, stream_detector=None, repeated_parallel_call_threshold=None, action="error")
    # Explicit tool name matches the common schema; native validation remains enabled.
    from pydantic_ai import Tool
    agent = Agent(FunctionModel(response), tools=[Tool(obs.read, name="read_evidence")],
                  system_prompt=runtime.SYSTEM, capabilities=[detector])
    result = agent.run_sync(config["task"] + "\nSynthetic source: " + obs.case["source_text"],
                           usage_limits=UsageLimits(request_limit=protocol["model_call_limit"],
                                                    tool_calls_limit=protocol["tool_call_limit"]))
    obs.events.append({"kind": "native_messages", "messages": json.loads(result.all_messages_json())})
    obs.feedback(json.loads(result.all_messages_json()), "pydantic")
    return "COMPLETED", json.loads(result.output)


