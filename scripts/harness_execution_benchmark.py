def dependency_manifest():
    """Verify every locked distribution and RECORD-covered installed file."""
    expected = dict(re.findall(r"^([A-Za-z0-9_.-]+)==([^\s;]+)", LOCK.read_text(encoding="utf-8"), re.M))
    expected = {name.lower().replace("_", "-"): value for name, value in expected.items()}
    inventory = {}
    for dist in distributions():
        name = dist.metadata["Name"].lower().replace("_", "-")
        context.require(name not in inventory, "duplicate installed distribution")
        context.require(name in expected or name in {"pip", "setuptools", "wheel"}, "unlocked runtime distribution: " + name)
        record = dist.read_text("RECORD")
        context.require(record is not None, "installed distribution RECORD missing: " + name)
        verified = 0
        for path, encoded, size in csv.reader(io.StringIO(record)):
            if not encoded:
                continue  # Generated bytecode and RECORD itself have no wheel hash.
            algorithm, wanted = encoded.split("=", 1)
            context.require(algorithm == "sha256", "unsupported installed file hash")
            data = Path(dist.locate_file(path)).read_bytes()
            actual = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).decode().rstrip("=")
            context.require(actual == wanted and (not size or len(data) == int(size)), "installed file identity changed: " + name)
            verified += 1
        inventory[name] = {"version": dist.version, "record_sha256": hashlib.sha256(record.encode()).hexdigest(),
                           "verified_files": verified, "role": "runtime" if name in expected else "environment_bootstrap"}
    context.require(all(name in inventory and inventory[name]["version"] == value for name, value in expected.items()),
                    "installed versions do not match complete benchmark lock")
    return inventory


def validate_cases(cases):
    context.require(isinstance(cases, list) and cases, "nonempty case list required")
    seen = set()
    for case in cases:
        context.require(isinstance(case, dict) and isinstance(case.get("id"), str) and case["id"] not in seen,
                        "unique case id required")
        seen.add(case["id"])
        context.require(case.get("family") in FAMILIES, "unknown family")
        context.require(isinstance(case.get("source_text"), str) and len(case["source_text"]) >= 64,
                        "explicit synthetic source text required")
        context.require("synthetic" in case["source_text"].lower(), "synthetic disclosure required")
        context.require(type(case.get("repeat_last")) is bool, "repeat_last boolean required")
        context.require(case.get("expected") in {"completed", "bounded_stop", "refused", "provider_failed"}, "unknown expected outcome")
        context.require(case.get("expected_disposition") in {None, "NO_FLAG", "ABSTAIN"}, "unknown disposition")
        context.require(isinstance(case.get("expected_excerpt_offsets"), list), "expected offsets required")
        for offset in case["expected_excerpt_offsets"]:
            context.integer(offset, "expected offset")
        steps = case.get("steps")
        context.require(isinstance(steps, list) and steps, "script required")
        for step in steps:
            context.require(isinstance(step, dict) and step.get("kind") in {"tool", "answer", "timeout"}, "invalid step")
            if step["kind"] == "tool":
                context.require(isinstance(step.get("args"), dict) and isinstance(step.get("name"), str)
                                and isinstance(step.get("call_id"), str) and step["call_id"], "invalid tool step")
            if step["kind"] == "answer":
                context.require(step.get("disposition") in {"NO_FLAG", "ABSTAIN"}
                                and isinstance(step.get("reason"), str) and step["reason"], "invalid answer")
        index = case.get("mutate_after_step")
        context.require(index is None or (type(index) is int and 0 <= index < len(steps)), "invalid mutation index")
    return cases


